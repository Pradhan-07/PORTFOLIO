import { useCallback, useEffect, useState } from 'react';

export interface ContributionDay {
  date: string;
  count: number;
  level: number;
}

interface GitHubSnapshotFile {
  fetchedAt?: string;
  contributions?: {
    totalLastYear?: number;
    currentStreak?: number;
    longestStreak?: number;
    days?: ContributionDay[];
  };
}

export interface ContributionsSnapshot {
  status: 'loading' | 'ready' | 'unavailable';
  days: ContributionDay[];
  totalLastYear: number;
  currentStreak: number;
  longestStreak: number;
  fetchedAt: string | null;
  reload: () => void;
}

/** Heatmap cell colour for a contribution level — shared by the streak tracker and the bottom-bar strip. */
export function contributionLevelColor(level: number, count: number): string {
  if (count === 0 || level === 0) return 'color-mix(in srgb, var(--bg) 90%, #151815)';
  if (level === 1) return '#224a24';
  if (level === 2) return '#2f6c32';
  if (level === 3) return '#459c4a';
  return '#66cc6a';
}

/**
 * Reads the build-time contribution snapshot from `/data/github-snapshot.json`
 * (same-origin; generated by scripts/generate-snapshots.mjs — G8). No
 * third-party API is called at runtime. On any failure the state resolves
 * to 'unavailable' and consumers must show an honest neutral state — never
 * invented numbers.
 */
export function useContributionsSnapshot(): ContributionsSnapshot {
  const [days, setDays] = useState<ContributionDay[]>([]);
  const [totals, setTotals] = useState({ totalLastYear: 0, currentStreak: 0, longestStreak: 0 });
  const [fetchedAt, setFetchedAt] = useState<string | null>(null);
  const [status, setStatus] = useState<'loading' | 'ready' | 'unavailable'>('loading');
  const [attempt, setAttempt] = useState(0);

  const reload = useCallback(() => setAttempt((n) => n + 1), []);

  useEffect(() => {
    let cancelled = false;
    setStatus('loading');
    fetch('/data/github-snapshot.json')
      .then((res) => {
        if (!res.ok) throw new Error(`HTTP ${res.status}`);
        return res.json() as Promise<GitHubSnapshotFile>;
      })
      .then((json) => {
        if (cancelled) return;
        const contributions = json.contributions;
        if (!contributions || !Array.isArray(contributions.days)) {
          throw new Error('Snapshot file is missing contribution data');
        }
        const sorted = [...contributions.days].sort((a, b) => (a.date < b.date ? -1 : 1));
        setDays(sorted);
        setTotals({
          totalLastYear:
            contributions.totalLastYear ?? sorted.reduce((sum, d) => sum + d.count, 0),
          currentStreak: contributions.currentStreak ?? 0,
          longestStreak: contributions.longestStreak ?? 0,
        });
        setFetchedAt(json.fetchedAt ?? null);
        setStatus('ready');
      })
      .catch((err) => {
        if (cancelled) return;
        console.warn('Could not load GitHub snapshot:', err);
        setStatus('unavailable');
      });
    return () => {
      cancelled = true;
    };
  }, [attempt]);

  return { status, days, ...totals, fetchedAt, reload };
}
